// THE NATION'S FLOOR PER RESIDENT, BY CLASS AND BY WHERE ITS INDUSTRY SITS.
//
// The town generator (src/citygen/demand.mjs) sizes each class of building
// from what the region's people need. That need comes from the engine's own
// industry table (src/engine/industries.ts: CES 2023 employment, the share
// working off a commercial floor, the share working from home, feet a
// worker) — the same numbers the engine's firms rent by. The generator is
// plain JavaScript and cannot import the engine's TypeScript, so this tool
// bundles the table and writes the derived figures to
// src/citygen/floorDemand.mjs. `--check` fails if that file has drifted from
// the engine (run it after changing industries.ts or industryData.ts).
//
// Each industry is filed under its NAICS sector so the generator can read
// where in a metro that sector's jobs sit (Kneebone 2009, Table 3; see
// demand.mjs). Rows are summed by (class, sector).
//
//   node tools/floor-demand.mjs           rewrite src/citygen/floorDemand.mjs
//   node tools/floor-demand.mjs --check   exit 1 if it is stale
import { buildSync } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(APP, "src/citygen/floorDemand.mjs");

const entry = `
import { INDUSTRIES, INDUSTRY_IDS, OFF_FLOOR, REMOTE, floorOf, BEA_CODES } from "./src/engine/industries";
import { PARTICIPATION, OPENING_UNEMP, OPENING_VAC, SF_PER_HOME, PEOPLE_PER_HOME } from "./src/engine/market";
export { INDUSTRIES, INDUSTRY_IDS, OFF_FLOOR, REMOTE, floorOf, BEA_CODES, PARTICIPATION, OPENING_UNEMP, OPENING_VAC, SF_PER_HOME, PEOPLE_PER_HOME };
`;
const out = buildSync({ stdin: { contents: entry, resolveDir: APP, loader: "ts" }, bundle: true, format: "esm", write: false, platform: "node", logLevel: "error" });
const M = await import("data:text/javascript;base64," + Buffer.from(out.outputFiles[0].text).toString("base64"));

// The NAICS sector Kneebone's Table 3 files each BEA summary code under.
// Government and "other services" are not in County Business Patterns, so
// they take the all-jobs row ("all").
function sectorOf(bea) {
  if (bea.startsWith("G") || bea === "81") return "all";
  if (bea.startsWith("ORE") || bea === "532RL") return "53";
  if (bea === "4A0" || bea.startsWith("44") || bea.startsWith("45")) return "44";
  if (bea === "487OS" || bea.startsWith("48") || bea.startsWith("49")) return "48";
  for (const p of ["22", "23", "42", "51", "52", "53", "54", "55", "56", "61", "62", "71", "72"]) if (bea.startsWith(p)) return p;
  if (bea[0] === "3") return "3";
  return "all";
}

// Jobs per resident at the opening, the engine's own: the labour force over
// the population, times the employed share (market.ts `citySize`).
const JOBS_PER_CAP = M.PARTICIPATION * (1 - M.OPENING_UNEMP);
const metro = M.INDUSTRY_IDS.filter((k) => M.INDUSTRIES[k].where !== "outside");
const tot = metro.reduce((a, k) => a + M.INDUSTRIES[k].empK, 0);
// one row per industry: its class, its Kneebone sector, its feet and its
// workers per resident, and whether it is TRADED — sells beyond the town (the
// NAICS sectors Census County Business Patterns concentrations were measured
// over in src/citygen/specialty.mjs: manufacturing, wholesale, transport,
// information, finance, professional services, headquarters)
const TRADED = (bea) => bea[0] === "3" || ["42", "48", "49", "51", "52", "54", "55"].some((p) => bea.startsWith(p)) || bea === "487OS";
const rows = [];
for (const k of metro) {
  const I = M.INDUSTRIES[k];
  const on = (1 - M.OFF_FLOOR[k]) * (1 - M.REMOTE[k]);
  if (!(on > 0) || !(I.sfPerWorker > 0)) continue;
  const bea = M.BEA_CODES[k][0];
  const sf = JOBS_PER_CAP * (I.empK / tot) * on * I.sfPerWorker, jobs = JOBS_PER_CAP * (I.empK / tot) * on;
  rows.push(`  { id: "${k}", cls: "${M.floorOf(k)}", sector: "${sectorOf(bea)}", traded: ${TRADED(bea)}, sf: ${sf.toFixed(3)}, jobs: ${jobs.toFixed(5)} },`);
}
rows.sort();
const text = `// GENERATED by tools/floor-demand.mjs from src/engine/industries.ts and
// market.ts — do not edit; rerun the tool. [D]
//
// Feet of each commercial class a resident of an American region occupies,
// at work, by the NAICS sector of the industry renting it: jobs per resident
// (${M.PARTICIPATION} participation x ${1 - M.OPENING_UNEMP} employed) x the industry's share of
// US employment (CES 2023) x the share working on a commercial floor and not
// from home x the feet a worker takes; and those workers per resident (jobs). One row per industry.
export const FLOOR_PER_RESIDENT = [
${rows.join("\n")}
];
/** Jobs per resident at the opening: participation x the employed share (market.ts citySize). */
export const JOBS_PER_RESIDENT = ${JOBS_PER_CAP.toFixed(4)};
/** Stock of flats per resident: the engine's feet a home over people a household. */
export const HOME_SF_PER_RESIDENT = ${(M.SF_PER_HOME / M.PEOPLE_PER_HOME).toFixed(3)};
/** The engine's opening vacancy by class: stock is what is occupied over (1 - this). */
export const OPENING_VAC = ${JSON.stringify(M.OPENING_VAC)};
`;

if (process.argv.includes("--check")) {
  const now = readFileSync(OUT, "utf8");
  if (now !== text) { console.error("src/citygen/floorDemand.mjs is stale: run node tools/floor-demand.mjs"); process.exit(1); }
  console.log("floorDemand.mjs matches the engine");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${rows.length} rows)`);
}
