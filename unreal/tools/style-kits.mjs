// The generated facade styles, as the Build desk offers them.
//   node unreal/tools/style-kits.mjs
// Reads unreal/tools/styles.json (the recipes make-styles.py builds) and writes
// broadway-and-wall/src/engine/styleKits.ts, which renderView.ts appends to its
// KITS. A style is listed only when its kit table exists (Data/kit-<KEY>.json),
// so a style scrapped in review disappears from the desk with its kit.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DATA = join(HERE, "..", "BroadwayWall", "Data");
const OUT = join(HERE, "..", "..", "broadway-and-wall", "src", "engine", "styleKits.ts");
const ERA = { prewar: "1850-1915", interwar: "1915-1945", postwar: "1945-1995", contemporary: "1995-2025" };

const styles = JSON.parse(readFileSync(join(HERE, "styles.json"), "utf8"))
  .filter((r) => existsSync(join(DATA, `kit-${r.key}.json`)));
const rows = styles.map((r) => ({
  key: r.key,
  name: r.label,
  era: r.era ?? ERA[r.group] ?? "1850-2020",
  group: r.group in ERA ? r.group : "postwar",
  family: (r.families ?? [])[0] ?? (r.group === "postwar" ? "modern" : "brick"),
}));
const body = rows.map((k) => `  { ${Object.entries(k).map(([f, v]) => `${f}: ${JSON.stringify(v)}`).join(", ")} },`).join("\n");
writeFileSync(OUT, `// GENERATED by unreal/tools/style-kits.mjs from unreal/tools/styles.json — do not edit.
// Broadway & Wall's own facade styles (unreal/tools/make-styles.py), as the Build desk offers them.
export const STYLE_KITS: { key: string; name: string; era: string; group: "prewar" | "interwar" | "postwar" | "contemporary"; family: string }[] = [
${body}
];
`);
console.log(`styleKits.ts: ${rows.length} styles`);
