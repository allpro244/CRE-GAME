// Tables for a century-dev.mjs run: node tools/mdga/century-dev-report.mjs run.json > out.md
import { readFileSync } from "node:fs";
const r = JSON.parse(readFileSync(process.argv[2], "utf8"));
const K = (n) => (n == null || !Number.isFinite(n) ? "—" : Math.abs(n) >= 1e9 ? `$${(n / 1e9).toFixed(2)}B` : Math.abs(n) >= 1e6 ? `$${(n / 1e6).toFixed(1)}M` : `$${(n / 1e3).toFixed(0)}K`);
const P = (x, d = 1) => (x == null || !Number.isFinite(x) ? "—" : `${(x * 100).toFixed(d)}%`);
const L = (s = "") => console.log(s);
const U = ["office", "multifamily", "retail", "industrial"];
const ab = { office: "Off", multifamily: "MF", retail: "Ret", industrial: "Ind" };

L(`## Economics every 20 years`);
L();
L(`| Year | Phase | Index | CPI | Cost idx | City jobs | Pop | Buildings | Vacant lots | Floor area | Land $/sf (med / p90) |`);
L(`|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|`);
for (const s of r.snaps) L(`| ${s.y} | ${s.phase} | ${s.idx.toFixed(2)}% | ${s.cpi.toFixed(2)} | ${s.costIdx.toFixed(2)} | ${s.jobsCity.toLocaleString()} | ${s.pop.toLocaleString()} | ${s.buildings.toLocaleString()} | ${s.vacantLots.toLocaleString()} | ${(s.floorSf / 1e6).toFixed(1)}M sf | $${s.landPsfMedian} / $${s.landPsfP90} |`);
L();
L(`| Year | ${U.map((u) => `${ab[u]} rent $/sf`).join(" | ")} | ${U.map((u) => `${ab[u]} vac`).join(" | ")} | ${U.map((u) => `${ab[u]} cap`).join(" | ")} |`);
L(`|---|${U.map(() => "--:").join("|")}|${U.map(() => "--:").join("|")}|${U.map(() => "--:").join("|")}|`);
for (const s of r.snaps) L(`| ${s.y} | ${U.map((u) => `$${s.rent[u].toFixed(2)}`).join(" | ")} | ${U.map((u) => P(s.vac[u])).join(" | ")} | ${U.map((u) => P(s.cap[u], 2)).join(" | ")} |`);
L();
L(`## The firm every 20 years`);
L();
L(`| Year | Net worth | Cash | Line drawn | Deeds | Live jobs | Book value | Debt | NOI/yr | Rank | Leader (equity) | Jobs started | Sales |`);
L(`|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|---|--:|--:|`);
for (const s of r.snaps) L(`| ${s.y} | ${K(s.nw)} | ${K(s.cash)} | ${K(s.line)} | ${s.deeds} | ${s.liveJobs} | ${K(s.bookValue)} | ${K(s.debt)} | ${K(s.noi)} | #${s.rank}/${s.field} | ${s.top5[0].name} (${K(s.top5[0].eq)}) | ${s.started} | ${s.sold} |`);
L();
L(`## Every development`);
L();
L(`| # | Start | Address | Use | Floors | GSF | Lot sf | Land | All-in cost | $/sf all-in | Hard $/sf | Loan | LTC | Rate | Equity | YoC | Exit yld | Hurdle | Mkt rent $/sf | City vac | Index | Phase |`);
L(`|--:|---|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|---|`);
for (const j of r.jobs) L(`| ${j.n} | ${j.startY} | ${j.address} | ${j.use} | ${j.floors} | ${j.gsf.toLocaleString()} | ${j.lotSf.toLocaleString()} | ${K(j.landBasis)} | ${K(j.basisTotal)} | $${j.allInPsf} | $${j.hardPsf} | ${K(j.loan)} | ${P(j.ltc, 0)} | ${j.rate}% | ${K(j.equity)} | ${j.yoc}% | ${j.exitYield}% | ${j.hurdle}x | $${j.mktRentPsf} | ${P(j.cityVac)} | ${j.idx}% | ${j.phase} |`);
L();
L(`| # | Delivered | Slip (mo) | Value at delivery | Basis | Mini-perm | Months to 90% | Sold | Sale price | Gain | Held (mo) | Levered IRR |`);
L(`|--:|---|--:|--:|--:|---|--:|---|--:|--:|--:|--:|`);
for (const j of r.jobs) L(`| ${j.n} | ${j.deliveredY ?? "—"} | ${j.slip ?? "—"} | ${K(j.valueAtDelivery)} | ${K(j.basisBooked)} | ${j.miniPerm ? `${K(j.miniPerm.bal)} @${j.miniPerm.rate}%` : "—"} | ${j.stabM ?? "—"} | ${j.sale?.y ?? "held"} | ${K(j.sale?.price)} | ${K(j.sale?.gain)} | ${j.sale?.heldM ?? "—"} | ${j.sale?.irr != null ? P(j.sale.irr) : "—"} |`);
L();
L(`## Every sale`);
L();
L(`| Year | What | Address | Price | $/sf | Basis | Gain | Held | IRR | Cap rate then | Vac then | Index | Phase |`);
L(`|---|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|---|`);
for (const s of r.sales) L(`| ${s.y} | ${s.forced ? "**FORCED** " : ""}${s.kind} | ${s.address} | ${K(s.price)} | ${s.psf ? "$" + s.psf : "—"} | ${K(s.basis)} | ${K(s.gain)} | ${s.heldM} mo | ${s.irr != null ? P(s.irr) : "—"} | ${P(s.capRate, 2)} | ${P(s.vac)} | ${s.idx}% | ${s.phase} |`);
L();
L(`## Land bought`);
L();
L(`| Year | Address | Lot sf | Price | $/sf | How | Financing |`);
L(`|---|---|--:|--:|--:|---|---|`);
for (const b of r.landBuys) L(`| ${b.y} | ${b.address} | ${Math.round(b.lotSf).toLocaleString()} | ${K(b.price)} | $${(b.price / b.lotSf).toFixed(0)} | ${b.how} | ${b.loan ? `land loan ${K(b.loan.bal)} @${b.loan.rate?.toFixed(2)}%` : "cash"} |`);
L();
L(`## Final league table`);
L();
L(`| Rank | Firm | Style | Equity | Deeds |`);
L(`|--:|---|---|--:|--:|`);
r.finalBoard.forEach((b, i) => L(`| ${i + 1} | ${b.name === "You" ? "**You**" : b.name} | ${b.style} | ${K(b.eq)} | ${b.bldgs} |`));
L();
L(`Counters: \`${JSON.stringify(r.counters)}\``);
L();
L(`Tape: \`${JSON.stringify(r.tape)}\` · off-market: \`${JSON.stringify(r.offMarket)}\``);
L();
L(`Friction: ${Object.entries(r.friction).sort((a, b) => b[1] - a[1]).slice(0, 12).map(([k, v]) => `${v}× ${k}`).join(" · ")}`);
